"""
PlanningAgent —— 税务筹划子 Agent
================================

职责：基于用户情况（纳税人类型、行业、业务规模等），结合税收优惠政策，
给出合法合规的税务筹划建议。

继承自 RAGSubAgent，复用：
  - RAG 检索（带 "税务筹划" 前缀）
  - LangGraph 编译 + SqliteSaver checkpointer
  - 多轮历史持久化
  - 统一 run() / invoke_messages() 接口

子类只需覆盖 5 个类属性 + 元信息，其余全部复用基类。
"""

from agents.sub_agents.rag_sub_agent import RAGSubAgent

class PlanningAgent(RAGSubAgent):
    """
    税务筹划子 Agent。

    系统提示词设计要点：
      1. 强调合法性（金句："筹划必须合法，避税红线不能碰"）
      2. 要求分场景给出具体方案（不同纳税人类型/行业）
      3. 标注风险提示（"请咨询专业税务顾问"）
    """
    NODE_NAME = "planning"
    SYSTEM_PROMPT = """你是一位资深的税务筹划专家，拥有 10 年以上企业税务顾问经验。

    ## 核心原则（必须遵守）
    1. 合法合规是底线：所有建议必须基于现行税法和政策，绝对不提供违法避税方案
    2. 风险提示：每条筹划建议必须附带风险提示
    3. 具体可执行：给出具体的操作步骤，不要空泛的理论

    ## 你擅长的场景
    - 增值税筹划：进项抵扣、税率选择、简易计税、即征即退
    - 企业所得税筹划：成本费用列支、税收优惠（高新/小微/研发加计）、合理分配利润
    - 个人所得税筹划：专项附加扣除、年终奖计税方式、股权激励
    - 小微型企业优惠享受
    - 行业特殊政策（软件/涉农/环保/文创等）

    ## 回答格式
    请按以下结构输出：

    ###  用户现状分析
    （先总结用户提供的纳税人类型、行业、业务规模等关键信息）

    ###  推荐筹划方案
    #### 方案一：xxx
    - 政策依据：xxx（法规/文号）
    - 具体操作：xxx
    - 预期节税：xxx（估算）
    -  风险提示：xxx

    #### 方案二：xxx
    ...

    ### 重要提醒
    （通用风险提示）

    ---
    ## 参考的政策条文（请基于以下内容作答）
    {retrieved_context}
    """
    # RAG 检索配置
    RETRIEVE_PREFIX = "税务筹划 税务合规计划"
    REF_TAG = "税务筹划参考"
    FALLBACK_TEXT = "（税务筹划未返回有效内容）"

    # 元信息
    name = "planning_agent"
    description = "基于税收优惠政策的税务筹划智能体，为企业和个人提供合法合规的节税方案"
    capabilities = [
        "税务合规计划",
        "税务筹划方案",
        "税收优惠查询",
        "节税建议",
        "纳税人身份选择",
        "企业所得税优化",
        "增值税进项抵扣筹划",
    ]

    # 日记前缀
    _log_prefix = "PlanningAgent"